clear; clc; monocopter_params; close all;

%% =========================================================================
%% 1. Parameter Discrete Kalman Filter
%% =========================================================================
Ts = 0.005;

Ad = [1, Ts;
      0, 1];

Cd = [1, 0];

Q = [0.001, 0;
     0,     0.003];

R = 0.03;

% Initial covariance
P = eye(2);

%% =========================================================================
%% 2. Jumlah iterasi
%% =========================================================================
N = 400;

% Iterasi tambahan untuk memperoleh nilai steady-state
N_ss = 10000;

%% =========================================================================
%% 3. Penyimpanan histori
%% =========================================================================

K_hist = zeros(N_ss, 2);

% Urutan:
% P11 = kolom 1
% P12 = kolom 2
% P21 = kolom 3
% P22 = kolom 4
P_hist = zeros(N_ss, 4);

%% =========================================================================
%% 4. Rekursi Discrete Kalman Filter
%% =========================================================================

for k = 1:N_ss

    % Prediction covariance
    P_priori = Ad * P * Ad' + Q;

    % Kalman Gain
    K = P_priori * Cd' / ...
        (Cd * P_priori * Cd' + R);

    % Correction covariance
    P = (eye(2) - K * Cd) * P_priori;

    % Simpan Kalman Gain
    K_hist(k,:) = K';

    % Simpan kovarians
    P_hist(k,:) = P(:)';
end

%% =========================================================================
%% 5. Iterasi yang ditampilkan pada tabel
%% =========================================================================

k_table = [1 5 10 20 100 200 400];

% Waktu
time_table = k_table * Ts;

% Kalman Gain
K1_table = K_hist(k_table,1);
K2_table = K_hist(k_table,2);

% Kovarians
P11_table = P_hist(k_table,1);
P22_table = P_hist(k_table,4);

%% =========================================================================
%% 6. Nilai steady-state
%% =========================================================================

K_inf = K_hist(end,:)';

P_inf = reshape(P_hist(end,:),2,2);

%% =========================================================================
%% 7. Buat tabel
%% =========================================================================

T = table( ...
    k_table', ...
    time_table', ...
    K1_table, ...
    K2_table, ...
    P11_table, ...
    P22_table, ...
    'VariableNames', { ...
    'Iterasi_k', ...
    'Waktu_s', ...
    'K1', ...
    'K2', ...
    'P11', ...
    'P22'});

%% =========================================================================
%% 8. Tampilkan tabel
%% =========================================================================

disp(' ');
disp('======================================================================');
disp(' EVOLUSI KALMAN GAIN DAN KOVARIANS MENUJU STEADY-STATE');
disp(' KANAL ROLL');
disp('======================================================================');

disp(T);

%% =========================================================================
%% 9. Tampilkan nilai steady-state
%% =========================================================================

fprintf('\n======================================================================\n');
fprintf(' STEADY-STATE KALMAN FILTER\n');
fprintf('======================================================================\n');

fprintf('K1_inf  = %.8f\n', K_inf(1));
fprintf('K2_inf  = %.8f\n', K_inf(2));

fprintf('\nP_inf =\n');
fprintf('[ %.8f   %.8f ]\n', P_inf(1,1), P_inf(1,2));
fprintf('[ %.8f   %.8f ]\n', P_inf(2,1), P_inf(2,2));

%% =========================================================================
%% 10. Format tabel untuk langsung dimasukkan ke skripsi
%% =========================================================================

fprintf('\n======================================================================\n');
fprintf(' FORMAT TABEL SKRIPSI\n');
fprintf('======================================================================\n');

fprintf('\n%-10s %-12s %-12s %-12s %-12s %-12s\n', ...
    'Iterasi', 'Waktu(s)', 'K1', 'K2', 'P11', 'P22');

fprintf('-----------------------------------------------------------------------\n');

for i = 1:length(k_table)

    fprintf('%-10d %-12.3f %-12.4f %-12.4f %-12.5f %-12.5f\n', ...
        k_table(i), ...
        time_table(i), ...
        K1_table(i), ...
        K2_table(i), ...
        P11_table(i), ...
        P22_table(i));
end

% Baris steady-state
fprintf('%-10s %-12s %-12.4f %-12.4f %-12.5f %-12.5f\n', ...
    'inf', '--', ...
    K_inf(1), ...
    K_inf(2), ...
    P_inf(1,1), ...
    P_inf(2,2));